import {it,expect,vi,afterEach} from 'vitest';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {unzipSync} from 'fflate';
import {readDocument} from '../src/desktop/documents';
import {recognizeChemistryFigures} from '../src/desktop/chemistry-figures';
import {emptyProject} from '../src/core/model';
import {chemQuestionSchema} from '../src/core/chemistry';
import {completeFigureLinks} from '../src/core/chemistry-figure-links';
import {Store} from '../src/desktop/store';
import {exportPpt} from '../src/desktop/export';
import {callAI} from '../src/desktop/ai';
import truth from './fixtures/chemistry-figures/ground-truth.json';
vi.mock('../src/desktop/ai',()=>({callAI:vi.fn()}));
const ai=vi.mocked(callAI),settings={provider:'openai' as const,model:'fixture',baseUrl:'https://api.openai.com/v1'},dirs:string[]=[];
afterEach(async()=>{vi.resetAllMocks();for(const dir of dirs)await fs.rm(dir,{recursive:true,force:true});dirs.length=0;});
it('真实两页PDF渲染包含矢量流程、位图装置、跨页续图与统计图，缓存/PPT/备份往返保留',async()=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'figure-pdf-'));dirs.push(dir);const store=new Store(dir);
 const {source,bytes}=await readDocument(path.resolve('tests/fixtures/chemistry-figures/paper.pdf'),'paper');
 const p=emptyProject('合成PDF','chemistry');source.asset='sources/'+source.id+'.pdf';p.sources=[source];await store.asset(p.id,source.asset,bytes);
 for(const page of [1,2])ai.mockResolvedValueOnce({figures:truth.pdf.figures.filter(f=>f.page===page).map(f=>({name:f.id,kind:'other',description:f.id,questionNumbers:[f.questionNumber],box:Object.fromEntries(Object.entries(f.boundsNormalized).map(([k,v])=>[k,v*1000]))}))});
 await recognizeChemistryFigures(p,store.dir(p.id),settings,'synthetic',new AbortController().signal,async snapshot=>{await store.save(snapshot);});
 expect(p.sources[0].figures).toHaveLength(4);expect(p.sources[0].figureScanUnits).toEqual([1,2]);
 p.chemistry!.questions=['11','12','13'].map(number=>chemQuestionSchema.parse({id:'q'+number,number,stem:'合成题目',sourceId:source.id}));completeFigureLinks(p);
 expect(p.chemistry!.questions.map(q=>q.images.length)).toEqual([1,2,1]);for(const q of p.chemistry!.questions)q.confirmed=true;
 await store.save(p);const restored=await store.unpack(await store.pack(p.id));expect(restored.sources[0].figures).toEqual(p.sources[0].figures);expect(restored.chemistry).toEqual(p.chemistry);
 await recognizeChemistryFigures(restored,store.dir(restored.id),settings,'synthetic',new AbortController().signal,async()=>{});expect(ai).toHaveBeenCalledTimes(2);
 const file=path.join(dir,'figures.pptx');await exportPpt(p,file,p.chemistry!.questions.map(q=>'question:'+q.id));
 const files=unzipSync(new Uint8Array(await fs.readFile(file))),media=Object.entries(files).filter(([name])=>name.startsWith('ppt/media/'));
 for(const f of p.sources[0].figures!)expect(media.some(([,bytes])=>Buffer.from(bytes).equals(Buffer.from(f.data.split(',')[1],'base64')))).toBe(true);
},20000);
it('真实Word导入后自动提取两张嵌图并发送各自邻近题面',async()=>{
 const {source}=await readDocument(path.resolve('tests/fixtures/chemistry-figures/paper.docx'),'paper');const p=emptyProject('合成Word','chemistry');p.sources=[source];
 for(const number of ['21','22'])ai.mockResolvedValueOnce({figures:[{name:'图'+number,kind:'chart',description:'合成图',questionNumbers:[number],box:{x:0,y:0,width:1000,height:1000}}]});
 await recognizeChemistryFigures(p,'.',settings,'synthetic',new AbortController().signal,async()=>{});
 expect(source.figures).toHaveLength(2);expect(source.figures!.map(f=>f.questionNumbers)).toEqual([['21'],['22']]);
 expect(ai.mock.calls[0][3]).toContain('nearbyText');expect(ai.mock.calls[1][3]).toContain('22.');expect(ai.mock.calls[0][3]).not.toContain('base64');
});
